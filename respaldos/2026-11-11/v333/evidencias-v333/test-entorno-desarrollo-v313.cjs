const assert = require('node:assert/strict');
const {readFileSync} = require('node:fs');
const {runInNewContext} = require('node:vm');
const {join} = require('node:path');
const base = join(__dirname,'../v333-review');
const window = {};
runInNewContext(readFileSync(join(base,'config-v242.js'),'utf8'),{window,URLSearchParams});
const resolve = window.Hys314ResolverBackend;
const local = new URL('http://localhost:8042/');
const settings = {url:'http://127.0.0.1:54321/',publishableKey:'sb_publishable_ficticia'};
assert.equal(resolve(local,settings).url,'http://127.0.0.1:54321');
assert.notEqual(resolve(local,settings).storageKey,resolve(local,{...settings,url:'http://127.0.0.1:54322'}).storageKey);
assert.throws(()=>resolve(local,null),/Configura/);
assert.throws(()=>resolve(local,{...settings,url:'https://ujfsugivgysyhboyirtz.supabase.co'}),/Configura/);
assert.throws(()=>resolve(local,{...settings,publishableKey:'sb_secret_no_permitida'}),/publicable/);
assert.throws(()=>resolve(new URL('https://ejemplo.invalid/'),settings),/localhost/);
assert.throws(()=>resolve(local,{...settings,url:'http://127.0.0.1:65536/'}),/Configura/);
assert.ok(!readFileSync(join(base,'index.html'),'utf8').includes('ujfsugivgysyhboyirtz'));
console.log('Entorno local: 8 verificaciones superadas.');
